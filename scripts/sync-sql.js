/* Regenerates the knowledge supplement section in database/02-seed-w245.sql
   from demo/assets/js/data.js (codes+guides) and the local knowledge corpus.
   The knowledge corpus (api/_lib/knowledge.js) is the committed fallback.
   Idempotent: replaces the text between the BEGIN/END markers.
   Run: npm run sync-sql                                                        */
const fs = require('fs');
const vm = require('vm');

const ROOT = __dirname + '/..';
const src = fs.readFileSync(ROOT + '/demo/assets/js/data.js', 'utf8');
const { FAULT_CODES } = vm.runInContext(src + ';({FAULT_CODES})', vm.createContext({}));
const knowledge = JSON.parse(fs.readFileSync(ROOT + '/api/_lib/knowledge.js', 'utf8')
  .replace(/^\/\*[\s\S]*?\*\/\n/, '').replace(/^module\.exports = /, '').replace(/;\s*$/, ''));

const BEGIN = '-- >>> knowledge supplement (generated by scripts/sync-sql.js — run: npm run sync-sql. Do not edit by hand.)';
const END = '-- >>> end knowledge supplement <<<';
const SOURCE = 'W245 community digest';

const esc = s => String(s).replace(/\\/g, '\\\\').replace(/'/g, "''");

/* 1) supplementary fault codes: only entries generated from the RAG corpus */
const ragCodes = FAULT_CODES.filter(c => c.guide && c.guide.source === SOURCE);
const codeRows = ragCodes.map(c =>
  `('${esc(c.code)}','${esc(c.name)}','${esc(c.system)}','${c.severity}',\n` +
  ` '${JSON.stringify(c.symptoms)}',\n` +
  ` '${JSON.stringify(c.causes)}',\n` +
  `${c.dangerous},'mercedes-benz','W245')`);

/* 2) supplementary repair guides */
const guideRows = ragCodes.map(c =>
  `('${esc(c.code)}','${esc(c.guide.title)}',\n   '${JSON.stringify(c.guide.steps)}',\n   '${esc(c.guide.source)}')`);

/* 3) standalone knowledge chunks (guide_id null) */
const knowRows = knowledge.map(item => {
  const meta = JSON.stringify({ category: item.category || null, make: 'mercedes-benz',
    model_scope: 'W245', type: 'knowledge', code: (item.fault_codes || [])[0] || null });
  return `('${esc(item.q + ' — ' + item.a)}', '${esc(meta)}')`;
});

const block = `${BEGIN}

-- 79 supplementary fault codes from the cleaned community corpus (total codebook: ${FAULT_CODES.length})
insert into fault_codes (code, name, system, severity, symptoms, causes, dangerous, make, model_scope) values
${codeRows.join(',\n')};

-- repair guides for the supplementary codes
insert into repair_guides (fault_code_id, title, steps, source_ref, verified)
select f.id, g.title, g.steps::jsonb, g.ref, true
from (values
  ${guideRows.join(',\n  ')}
) as g(code, title, steps, ref)
join fault_codes f on f.code = g.code;

-- placeholder vectors for the supplementary guides (replaced by /api/ingest embeddings)
insert into kb_chunks (guide_id, chunk_text, embedding, metadata)
select r.id, r.title || ' — ' || (r.steps->>0), '[0,0]'::vector(768),
  jsonb_build_object('code', f.code, 'system', f.system, 'severity', f.severity,
                     'make', 'mercedes-benz', 'model_scope', 'W245')
from repair_guides r
join fault_codes f on f.id = r.fault_code_id
where f.code in (${ragCodes.map(c => `'${esc(c.code)}'`).join(',')});

-- standalone knowledge chunks (${knowledge.length} items: fuses · CVT · AC · sensors · doors · oils…) — guide_id is NULL
insert into kb_chunks (chunk_text, metadata, embedding) values
${knowRows.join(',\n')};

${END}`;

/* splice into the seed file */
const file = ROOT + '/database/02-seed-w245.sql';
let sql = fs.readFileSync(file, 'utf8');
const i1 = sql.indexOf(BEGIN), i2 = sql.indexOf(END);
if (i1 !== -1 && i2 !== -1) sql = sql.slice(0, i1) + block + '\n' + sql.slice(i2 + END.length);
else sql += '\n\n-- ============================================================\n' + block + '\n';
fs.writeFileSync(file, sql);

console.log('SQL supplement regenerated — codes:', ragCodes.length,
  '| guides:', guideRows.length, '| knowledge chunks:', knowRows.length);
