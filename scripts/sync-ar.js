/* sync-ar.js — generates database/03-seed-arabic.sql (Arabic content columns)
   from demo/assets/js/data.js + demo/assets/js/data-ar.js (Phase 6 localization).
   Idempotent: pure UPDATEs keyed by code — safe to re-run.
   Run: npm run sync-ar        Apply: psql $DSN -f database/03-seed-arabic.sql */
const fs = require('fs'), vm = require('vm');
const ROOT = __dirname + '/..';
const load = (f, names) => vm.runInContext(
  'var window = this; ' + fs.readFileSync(ROOT + f, 'utf8') + ';({ ' + names + ' })', vm.createContext({}));
const { FAULT_CODES } = load('/demo/assets/js/data.js', 'FAULT_CODES');
const AR = load('/demo/assets/js/data-ar.js', 'FAULT_CODES_AR').FAULT_CODES_AR;

const SYSTEM_AR = {
  'Ignition / Engine': 'الإشعال / المحرك',
  'Fuel & Air Metering': 'الوقود والهواء',
  'Cooling System': 'نظام التبريد',
  'Emissions': 'الانبعاثات',
  'Diesel Starting': 'تشغيل الديزل',
  'ESP / Steering': 'ESP / التوجيه',
  'ESP / Brakes': 'ESP / الفرامل',
  'HVAC': 'تكييف وتدفئة',
  'Electrical': 'كهرباء',
  'Transmission': 'ناقل الحركة',
  'Engine Timing': 'توقيت المحرك',
  'Boost Control': 'التحكم بالشحن',
  'Network / CAN': 'شبكة / CAN'
};
const fix = s => s.replace(/Recommended action:/g, 'الإجراء الموصى به:').replace(/Recommended action /g, 'الإجراء الموصى به: ');
const isAr = s => /[\u0600-\u06FF]/.test(s);
const esc = s => String(s).replace(/\\/g, '\\\\').replace(/'/g, "''");
const jsonb = v => "'" + esc(JSON.stringify(v)) + "'::jsonb";

let missing = [];
const rows = FAULT_CODES.map(c => {
  const full = AR.byCode[c.code];
  const name_ar = full ? full.name : (AR.names[c.name] || (isAr(c.name) ? c.name : null));
  const system_ar = isAr(c.system) ? c.system : (SYSTEM_AR[c.system] || c.system);
  const symptoms_ar = full ? full.symptoms : c.symptoms.map(fix);
  const causes_ar = full ? full.causes : c.causes.map(fix);
  const steps_ar = (full ? full.steps : c.guide.steps).map(fix);
  if (!name_ar) missing.push(c.code);
  const sql =
    `update fault_codes set name_ar='${esc(name_ar)}', system_ar='${esc(system_ar)}',` +
    ` symptoms_ar=${jsonb(symptoms_ar)}, causes_ar=${jsonb(causes_ar)} where code='${c.code}';\n` +
    `update repair_guides g set steps_ar=${jsonb(steps_ar)}` +
    ` from fault_codes f where g.fault_code_id=f.id and f.code='${c.code}';\n`;
  return sql;
}).join('\n');

const header = `-- 03-seed-arabic.sql — Arabic content columns (AUTO-GENERATED by scripts/sync-ar.js
-- — run: npm run sync-ar. Do not edit by hand.)
-- Requires the columns from 01-schema.sql (name_ar, system_ar, symptoms_ar,
-- causes_ar on fault_codes; steps_ar on repair_guides). Idempotent: re-runnable.

`;
fs.writeFileSync(ROOT + '/database/03-seed-arabic.sql', header + rows);
console.log('03-seed-arabic.sql written — codes:', FAULT_CODES.length, '| missing name_ar:', missing.length ? missing.join(',') : 'none');
