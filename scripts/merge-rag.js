/* Merges an optional local fault-code corpus into demo/assets/js/data.js.
   The generated supplement already ships with data.js; this tool is only
   needed when re-merging an updated local source folder (not part of the repo).
   - Expands small ranges (P0301-P0304 → 4 codes) and slash groups (P0016/P0017).
   - Large ranges (P0746-P0796, P1840-P1895) stay as one compact entry.
   - Idempotent: existing codes are never touched; re-running only refreshes the block.
   Run: npm run merge-rag                                                      */
const fs = require('fs');
const vm = require('vm');

const ROOT = __dirname + '/..';
const DATA = ROOT + '/demo/assets/js/data.js';
const RAG = ROOT + '/RAG&Fulte/fault_codes.json';   /* optional local source folder */
const SOURCE = 'W245 community digest';

if (!fs.existsSync(RAG)) {
  console.log('No local corpus folder (RAG&Fulte/fault_codes.json) — nothing to merge.');
  console.log('data.js already contains the merged supplement; this tool is optional.');
  process.exit(0);
}

const rag = JSON.parse(fs.readFileSync(RAG, 'utf8'));

/* base codes already in data.js (everything before the generated block) */
const wholeSrc = fs.readFileSync(DATA, 'utf8');
const cut = wholeSrc.split('/* ---------- RAG&Fulte')[0];
const baseSrc = cut !== wholeSrc ? cut + '];' : wholeSrc;   // close the truncated array
const existing = new Set(
  vm.runInContext(baseSrc + ';FAULT_CODES', vm.createContext({})).map(c => c.code));

/* ---------- expansion helpers ---------- */
function expandCode(code) {
  // "P0301-P0304" — full numeric codes on both sides, same letter prefix
  let m = code.match(/^([A-Z])(\d{4})-\1(\d{4})$/);
  if (m) {
    const lo = parseInt(m[2], 10), hi = parseInt(m[3], 10);
    if (hi > lo && hi - lo + 1 <= 10)
      return Array.from({ length: hi - lo + 1 }, (_, i) => m[1] + String(lo + i).padStart(4, '0'));
    return [code]; // big range stays compact
  }
  // "P0016/P0017" — slash group (numeric-ish members only)
  if (code.includes('/') && !code.includes(' ')) {
    const parts = code.split('/');
    if (parts.length <= 10 && parts.every(p => /^[A-Z0-9]+$/.test(p))) return parts;
    return [code];
  }
  return [code];
}

/* ---------- severity heuristic (documented, conservative) ---------- */
const HIGH_WORDS = ['ايرباج', 'SRS', 'ESP', 'ASR', 'تراكشن', 'Traction', 'تقطيع', 'Misfire', 'ABS'];
const LOW_WORDS = ['كشاف', 'زجاج', 'حساس حرارة', 'حرارة صالون', 'حرارة خارجية', 'حساس ضغط', 'مقعد',
  'مفتاح زجاج', 'تراسسوندر', 'لوحة تحكم سفلية', 'MOST', 'عصا', 'Group Fault', 'Switch Group'];
function severityFor(c) {
  const hay = (c.ar + ' ' + c.en + ' ' + (c.tip || ''));
  if (HIGH_WORDS.some(w => hay.toLowerCase().includes(w.toLowerCase()))) return 'HIGH';
  if (LOW_WORDS.some(w => hay.toLowerCase().includes(w.toLowerCase()))) return 'LOW';
  return 'MEDIUM';
}

/* ---------- build the new entries ---------- */
const entries = [];
for (const c of rag) {
  const codes = expandCode(c.code);
  const isRange = codes.length === 1 && /-|\/|\s/.test(c.code) && c.code !== codes[0];
  const name = isRange ? `${c.en} (${c.code})` : c.en;
  const tip = (c.tip || '').trim();
  const action = (c.action || '').trim();
  const steps = [];
  if (tip) steps.push(tip.charAt(0).toUpperCase() + tip.slice(1) + '.');
  if (action) steps.push(`Recommended action: ${action}.`);
  for (const code of codes) {
    if (entries.some(e => e.code === code)) continue;   // intra-run safety
    if (existing.has(code)) continue;                  // data.js already documents it (richer entry wins)
    const sev = severityFor(c);
    entries.push({
      code,
      name,
      severity: sev,
      system: c.system,
      symptoms: [c.ar],
      causes: tip ? [tip] : [],
      dangerous: sev === 'HIGH',
      guide: {
        title: `${c.en} — W245 (${c.system})`,
        steps: steps.length ? steps : ['Inspect the related system; confirm with live diagnostics before replacing parts.'],
        source: SOURCE
      }
    });
  }
}

/* ---------- splice into data.js ---------- */
let src = fs.readFileSync(DATA, 'utf8');
const START = `  /* ---------- W245 community corpus supplement`;
const firstIdx = src.indexOf(START);
const block = entries.map(e => {
  const esc = s => String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
  return `  { code: '${esc(e.code)}', name: '${esc(e.name)}',
    severity: SEV.${e.severity}, system: '${esc(e.system)}',
    symptoms: [${e.symptoms.map(s => `'${esc(s)}'`).join(', ')}],
    causes: [${e.causes.map(s => `'${esc(s)}'`).join(', ')}],
    dangerous: ${e.dangerous},
    guide: {
      title: '${esc(e.guide.title)}',
      steps: [${e.guide.steps.map(s => `'${esc(s)}'`).join(', ')}],
      source: '${esc(e.guide.source)}'
    }
  }`;
}).join(',\n');

const genHeader = `  /* ---------- W245 community corpus supplement (generated by scripts/merge-rag.js — run: npm run merge-rag. Do not edit by hand.) ---------- */\n`;
function ensureComma(s) {          // strip ALL trailing commas/whitespace, add exactly one
  return s.replace(/[,\s]+$/, '') + ',\n';
}
if (firstIdx !== -1) {
  // replace existing generated block: from START to the next '];'
  const endIdx = src.indexOf('];', firstIdx);
  src = ensureComma(src.slice(0, firstIdx)) + genHeader + block + ',\n' + src.slice(endIdx);
} else {
  // insert before the FAULT_CODES closing '];'
  const arrStart = src.indexOf('const FAULT_CODES = [');
  const endIdx = src.indexOf('];', arrStart);
  src = ensureComma(src.slice(0, endIdx)) + genHeader + block + ',\n' + src.slice(endIdx);
}
fs.writeFileSync(DATA, src);

/* ---------- verify ---------- */
const out = vm.runInContext(src + ';FAULT_CODES', vm.createContext({}));
console.log('merged — total codes:', out.length, '| added from RAG&Fulte:', entries.length);
const dupes = out.map(c => c.code).filter((c, i, a) => a.indexOf(c) !== i);
if (dupes.length) { console.error('DUPLICATE CODES:', dupes); process.exit(1); }
